from typing import Protocol

from .models import (
    ContentBlock,
    DocumentContext,
    EmbeddedChunk,
    ParsedDocument,
    PreparedFragment,
    SearchHit,
)


class DocumentParser(Protocol):
    def parse(self, data: bytes, context: DocumentContext) -> ParsedDocument: ...


class EmbeddingProvider(Protocol):
    def embed_batch(self, texts: list[str], purpose: str) -> list[list[float]]: ...


class TokenCounter(Protocol):
    tokenizer: object

    def count(self, text: str) -> int: ...
    def full_count(self, text: str, purpose: str = "document") -> int: ...


class ExternalContentProcessor(Protocol):
    def process(self, block: ContentBlock, context: DocumentContext) -> list[PreparedFragment]: ...


class VectorStore(Protocol):
    def upsert(self, chunks: list[EmbeddedChunk], result) -> None: ...
    def search(self, vector: list[float], filters: dict, top_k: int) -> list[SearchHit]: ...
    def verify_generation(self, generation_id: str, point_ids: list[str]) -> bool: ...
    def delete_generation(self, generation_id: str) -> None: ...


class JobRepository(Protocol):
    """Team adapter must persist jobs/outbox in one database transaction."""
    def create_with_outbox(self, job_id: str, document: DocumentContext) -> None: ...
    def claim(self, job_id: str, worker_id: str) -> bool: ...
    def complete(self, job_id: str, generation_id: str) -> None: ...
    def fail(self, job_id: str, error: str, retryable: bool) -> None: ...


class JobDelivery(Protocol):
    def publish(self, job_id: str) -> None: ...
    def acknowledge(self, message_id: str) -> None: ...
    def reclaim(self, idle_seconds: int) -> list[str]: ...
